-- =============================================================================
-- Etapa 1 · Esquema base: tipos, tabelas, índices e dados de referência
-- Todas as datas são timestamptz (UTC no banco). Exibição e cálculos de turno
-- usam America/Sao_Paulo.
-- =============================================================================

create type public.status_chamado as enum ('aberto', 'em_andamento', 'finalizado', 'cancelado');
create type public.situacao_prazo as enum ('dentro_do_prazo', 'fora_do_prazo');
create type public.origem_chamado as enum ('formulario', 'feishu', 'lark', 'api');
create type public.papel_usuario as enum ('tecnico', 'admin');
create type public.plataforma_notificacao as enum ('feishu', 'lark');

-- -----------------------------------------------------------------------------
-- Perfis da equipe (1:1 com auth.users). O login é "usuário ou matrícula";
-- internamente o e-mail do Auth é <login>@<AUTH_EMAIL_DOMAIN>.
-- -----------------------------------------------------------------------------
create table public.perfis (
  id                uuid primary key references auth.users (id) on delete cascade,
  login             text not null unique check (login ~ '^[a-z0-9][a-z0-9._-]{2,39}$'),
  nome              text not null check (char_length(trim(nome)) between 2 and 120),
  papel             public.papel_usuario not null default 'tecnico',
  ativo             boolean not null default true,
  deve_trocar_senha boolean not null default true,
  criado_em         timestamptz not null default now(),
  atualizado_em     timestamptz not null default now()
);

create table public.categorias (
  id     smallint generated by default as identity primary key,
  nome   text not null unique check (char_length(trim(nome)) between 2 and 60),
  ativo  boolean not null default true,
  ordem  smallint not null default 0
);

-- Turnos configuráveis. Intervalo [inicio, fim); se inicio > fim, vira a meia-noite.
create table public.turnos (
  id     smallint generated by default as identity primary key,
  nome   text not null unique check (char_length(trim(nome)) between 2 and 40),
  inicio time not null,
  fim    time not null,
  ordem  smallint not null default 0,
  check (inicio <> fim)
);

-- Linha única de configuração.
create table public.configuracoes (
  id                   boolean primary key default true check (id),
  sla_minutos          integer not null default 120 check (sla_minutos between 5 and 10080),
  alerta_minutos_antes integer not null default 30 check (alerta_minutos_antes between 1 and 1440),
  atualizado_em        timestamptz not null default now(),
  atualizado_por       uuid references public.perfis (id) on delete set null,
  check (alerta_minutos_antes < sla_minutos)
);

-- Tokens do webhook de entrada: um por canal, guardado só como hash SHA-256.
create table public.tokens_integracao (
  id            uuid primary key default gen_random_uuid(),
  nome          text not null check (char_length(trim(nome)) between 2 and 80),
  origem        public.origem_chamado not null check (origem <> 'formulario'),
  token_hash    text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  prefixo       text not null,
  ativo         boolean not null default true,
  criado_em     timestamptz not null default now(),
  criado_por    uuid references public.perfis (id) on delete set null,
  ultimo_uso_em timestamptz,
  revogado_em   timestamptz
);

-- Destinos de notificação (bots customizados de grupo do Feishu e do Lark).
-- A URL é restrita aos domínios oficiais para evitar envio a hosts arbitrários.
create table public.destinos_notificacao (
  id                uuid primary key default gen_random_uuid(),
  nome              text not null check (char_length(trim(nome)) between 2 and 80),
  plataforma        public.plataforma_notificacao not null,
  webhook_url       text not null unique,
  secret_assinatura text check (secret_assinatura is null or char_length(secret_assinatura) between 8 and 200),
  ativo             boolean not null default true,
  criado_em         timestamptz not null default now(),
  atualizado_em     timestamptz not null default now(),
  constraint destinos_url_oficial check (
       (plataforma = 'feishu' and webhook_url ~ '^https://open\.feishu\.cn/open-apis/bot/v2/hook/[A-Za-z0-9-]+$')
    or (plataforma = 'lark'   and webhook_url ~ '^https://open\.larksuite\.com/open-apis/bot/v2/hook/[A-Za-z0-9-]+$')
  )
);

-- -----------------------------------------------------------------------------
-- Chamados
-- numero, aberto_em, sla_minutos, prazo_limite e turno são preenchidos pelo
-- trigger de inserção (snapshot no momento da abertura).
-- -----------------------------------------------------------------------------
create sequence public.chamados_numero_seq as bigint;

create table public.chamados (
  id                        uuid primary key default gen_random_uuid(),
  numero                    text not null unique,

  solicitante_nome          text not null check (char_length(trim(solicitante_nome)) between 2 and 120),
  solicitante_setor         text not null check (char_length(trim(solicitante_setor)) between 1 and 80),
  solicitante_contato       text not null check (char_length(trim(solicitante_contato)) between 5 and 120),
  local                     text not null check (char_length(trim(local)) between 2 and 160),
  categoria_id              smallint not null references public.categorias (id),
  descricao                 text not null check (char_length(trim(descricao)) between 5 and 4000),
  foto_path                 text,
  origem                    public.origem_chamado not null,

  status                    public.status_chamado not null default 'aberto',
  turno                     text not null,
  aberto_em                 timestamptz not null default now(),
  sla_minutos               integer not null,
  prazo_limite              timestamptz not null,

  recebido_por              uuid references public.perfis (id),
  recebido_em               timestamptz,

  finalizado_por            uuid references public.perfis (id),
  finalizado_em             timestamptz,
  observacao_finalizacao    text,
  situacao_prazo            public.situacao_prazo,
  tempo_total_minutos       integer,
  tempo_ate_assumir_minutos integer,

  cancelado_por             uuid references public.perfis (id),
  cancelado_em              timestamptz,
  motivo_cancelamento       text,

  notificado_novo_em        timestamptz,
  alerta_prazo_enviado_em   timestamptz,
  atualizado_em             timestamptz not null default now(),

  constraint chamados_em_andamento_tem_responsavel
    check (status <> 'em_andamento' or (recebido_por is not null and recebido_em is not null)),
  constraint chamados_finalizado_completo
    check (status <> 'finalizado' or (
      recebido_por is not null and recebido_em is not null and finalizado_por is not null
      and finalizado_em is not null and situacao_prazo is not null and tempo_total_minutos is not null
      and char_length(trim(coalesce(observacao_finalizacao, ''))) >= 3)),
  constraint chamados_cancelado_completo
    check (status <> 'cancelado' or (
      cancelado_em is not null and char_length(trim(coalesce(motivo_cancelamento, ''))) >= 5))
);

create index chamados_status_prazo_idx    on public.chamados (status, prazo_limite);
create index chamados_aberto_em_idx       on public.chamados (aberto_em desc);
create index chamados_categoria_idx       on public.chamados (categoria_id);
create index chamados_recebido_por_idx    on public.chamados (recebido_por);
create index chamados_finalizado_por_idx  on public.chamados (finalizado_por);
create index chamados_cancelado_por_idx   on public.chamados (cancelado_por);
create index chamados_alerta_pendente_idx on public.chamados (prazo_limite)
  where status in ('aberto', 'em_andamento') and alerta_prazo_enviado_em is null;

-- Auditoria: toda mudança de status/responsável.
create table public.chamado_historico (
  id             bigint generated always as identity primary key,
  chamado_id     uuid not null references public.chamados (id) on delete cascade,
  acao           text not null check (acao in ('aberto', 'assumido', 'reatribuido', 'finalizado', 'cancelado')),
  status_de      public.status_chamado,
  status_para    public.status_chamado not null,
  usuario_id     uuid references public.perfis (id),
  responsavel_id uuid references public.perfis (id),
  comentario     text,
  criado_em      timestamptz not null default now()
);

create index chamado_historico_chamado_idx     on public.chamado_historico (chamado_id, criado_em);
create index chamado_historico_usuario_idx     on public.chamado_historico (usuario_id);
create index chamado_historico_responsavel_idx on public.chamado_historico (responsavel_id);
create index configuracoes_atualizado_por_idx  on public.configuracoes (atualizado_por);
create index tokens_integracao_criado_por_idx  on public.tokens_integracao (criado_por);

